from ADD_ROWID_AND_FIX_PUNCT_AND_BLEEPS import add_row_id, remove_trailing_punctuation, complete_bleeps
from FIX_INCOMPLETES import extract_incompletes
from CHECK_MULTISPEAKER_IN_INCOMPLETE_JSON import add_multispeaker_to_incomplete_json
from ADD_INCOMPLETE_ROW import remove_incomplete_duplicates
from READ_DICTATE import read_dictate
from CREATE_MENTIONS_JSON import create_mentions_json
from ADD_SPEAKER_REFERENCES_TO_JSON import add_speaker_references
from CHAIN_UP_MENTIONS_FROM_JSON import chain_up_mentions
from ADD_CATAPHORA_AND_FIRST_MENTION import reorder_mentions_in_chain, check_first_mention, check_cataphora
from CORRECT_NOT_CODE import correct_not_code
import os
import re
import json
import pandas as pd
from collections import defaultdict
from datetime import datetime, timedelta



def main(list_of_excels_and_dialoguejsons):                                 
	for excel, dialogue_json in list_of_excels_and_dialoguejsons:
		# EXTRACTING THE DIALOGUE NUMBER FROM THE EXCEL FILE NAME
		# Extract the file name without the path
		excel_file_short = os.path.basename(excel)
		dialogue_number_pattern = r'(\d{3})[xX&](\d{3})' # Our dialogue files all have the thre-digit IDs of the participants
		dialogue_number = re.match(dialogue_number_pattern, excel_file_short)
		if dialogue_number:
			dialogue_number = dialogue_number.group(0)
		else:
			# Input the dialogue number manually
			dialogue_number = input(f"Enter the dialogue number for file {excel}: ")
		excel_folder = os.path.dirname(excel)
		log_filename = f"{dialogue_number}_000_pipeline_log.txt"
		output_log = os.path.join(excel_folder, log_filename)

		print(f"Processing {dialogue_number}.", file=(open(output_log, 'a+')))
		# PIPELINE STEPS
			# Each step generates a new file, which is used as input for the next step
			# This way, if the pipeline is interrupted, it can be resumed from the last completed step
		# 1.- Add row ID
		excel_with_rowid = add_row_id(excel, excel_folder, dialogue_number)
		# 2.- Remove trailing punctuation in mentions
		excel_puntuation_fixed = remove_trailing_punctuation(excel_with_rowid, excel_folder, dialogue_number)
		# 3.- Complete BLEEPS so they're all in the format (BLEEP)
		excel_bleeps_fixed = complete_bleeps(excel_puntuation_fixed, excel_folder, dialogue_number)
		# 4.- Extract Incomplete json (file listing all the incomplete mentions)
		incomplete_json = extract_incompletes(excel_bleeps_fixed, dialogue_json, dialogue_number, output_log)
		# 5.- Add Multispeaker field to Incomplete json
		incomplete_json_with_multispeaker = add_multispeaker_to_incomplete_json(incomplete_json)
		# 6.- Add Incomplete column to Excel and delete duplicate entries generated by labelling incompletes in LabelStudio
		excel_with_incomplete = remove_incomplete_duplicates(incomplete_json_with_multispeaker, excel_bleeps_fixed, excel_folder, dialogue_number)
		# 7.- Add read-dictate column to Excel and delete duplicate entries generated by labelling read-dictate in LabelStudio
		excel_with_read_dictate = read_dictate(excel_with_incomplete, excel_folder, dialogue_number,output_log)
		# 8.- Create mentions JSON from the Excel file
		mentions_json = create_mentions_json(excel_with_read_dictate, dialogue_json, dialogue_number, output_log)
		# 9.- Extract speakers json and change the mentions json to include the speakers
		speaker_references_json_output_filepath, chains_json_with_speaker_references_filepath = add_speaker_references(excel_with_read_dictate, dialogue_json, dialogue_number, mentions_json)
		# 10.- Chain up mentions from the JSON file
		updated_chains_json = chain_up_mentions(chains_json_with_speaker_references_filepath, dialogue_number, excel_with_read_dictate, output_log)
		# 11.- Reorder mentions in chain JSON to be able to check first mentions
		ordered_chains_json = reorder_mentions_in_chain(updated_chains_json, dialogue_number, output_log)
		# 12.- Check first mentions in the ordered chains JSON
		chains_with_first_mentions = check_first_mention(ordered_chains_json, excel_with_read_dictate, dialogue_number)
		# 13.- Check cataphora in the chains JSON with first mentions checked
		chains_with_cataphora = check_cataphora(chains_with_first_mentions, dialogue_number, output_log)
		# 14.- Correct instances where Code Type says NOT code but there is a code referent
		chains_with_notcode = correct_not_code(chains_with_cataphora,dialogue_number)

		print(f"Processed {os.path.basename(excel)} with dialogue JSON {os.path.basename(dialogue_json)}.")

if __name__ == "__main__":
	list_of_excels_and_dialoguejsons = [("INSERT_PATH_TO_EXCEL_FILE_HERE", "INSERT_PATH_TO_DIALOGUE_JSON_FILE_HERE")]
	main(list_of_excels_and_dialoguejsons)

